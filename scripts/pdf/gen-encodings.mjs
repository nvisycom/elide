// Generate `crates/elide-pdf/src/pdf/reader/font/encoding/encodings.rs`: the
// glyph names of StandardEncoding, WinAnsiEncoding, MacRomanEncoding, the Mac
// OS Roman encoding a TrueType font reads by (9.6.5.4), and MacExpertEncoding
// (Annex D).
//
// The code-to-name pairs come from Apache PDFBox's encoding classes at a
// pinned commit, changed where PDFBox, Annex D, and the renderers differ:
//
// - WinAnsi 0xA0 and 0xAD are `space` and `hyphen` (PDFBox: `nbspace`,
//   `sfthyphen`, names the standard 14 AFMs do not have);
// - MacRoman 0xCA is `space` (PDFBox: `nbspace`);
// - MacRoman also has the Mac OS Roman entries of Table 113 but the Euro, as
//   PDFium and pdf.js read it (Annex D leaves those codes unused, and keeps
//   `currency` at 0xDB);
// - every WinAnsi code above octal 40 that Annex D leaves unused is `bullet`
//   (Annex D, note on WinAnsiEncoding; PDFBox does the same at runtime).
//
// Mac OS Roman is MacRoman with the Euro at 0xDB (Table 113). MacExpert comes
// from pdf.js at a pinned commit, as PDFBox has no table for it.
//
// Usage: node scripts/pdf/gen-encodings.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PDFBOX = "273e1ca7af365bf002b0189ddd1f476336853ac7";
const PDFJS = "81525fd446779f0a29003cf06e3ba33751954826";
const BASE = `https://raw.githubusercontent.com/apache/pdfbox/${PDFBOX}/pdfbox/src/main/java/org/apache/pdfbox/pdmodel/font/encoding`;

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = join(root, "crates/elide-pdf/src/pdf/reader/font/encoding/encodings.rs");

// The `{0NNN, "name"}` pairs of a PDFBox encoding class, as a 256-entry table.
async function table(file) {
  const response = await fetch(`${BASE}/${file}`);
  if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
  const source = await response.text();
  const names = new Array(256).fill(null);
  for (const [, code, name] of source.matchAll(/\{(0[0-7]+), "([^"]+)"\}/g)) {
    names[parseInt(code, 8)] = name;
  }
  return names;
}

const standard = await table("StandardEncoding.java");

const winAnsi = await table("WinAnsiEncoding.java");
winAnsi[0xa0] = "space";
winAnsi[0xad] = "hyphen";
for (let code = 0o41; code <= 0xff; code++) winAnsi[code] ??= "bullet";

const macRoman = await table("MacRomanEncoding.java");
macRoman[0xca] = "space";
const macOs = {
  0xad: "notequal", 0xb0: "infinity", 0xb2: "lessequal", 0xb3: "greaterequal",
  0xb6: "partialdiff", 0xb7: "summation", 0xb8: "product", 0xb9: "pi",
  0xba: "integral", 0xbd: "Omega", 0xc3: "radical", 0xc5: "approxequal",
  0xc6: "Delta", 0xd7: "lozenge", 0xf0: "apple",
};
for (const [code, name] of Object.entries(macOs)) macRoman[code] = name;

const macOsRoman = [...macRoman];
macOsRoman[0xdb] = "Euro";

// pdf.js's table: an array literal of 256 names, "" for an unused code.
async function pdfjs(name) {
  const url = `https://raw.githubusercontent.com/mozilla/pdf.js/${PDFJS}/src/core/encodings.js`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`encodings.js: HTTP ${response.status}`);
  const source = await response.text();
  const body = source.match(new RegExp(`const ${name} = \\[([\\s\\S]*?)\\];`))[1];
  const names = [...body.matchAll(/"([^"]*)"/g)].map(([, n]) => n || null);
  if (names.length !== 256) throw new Error(`${name}: ${names.length} codes`);
  return names;
}
const macExpert = await pdfjs("MacExpertEncoding");

function rust(name, doc, names) {
  const rows = [];
  for (let row = 0; row < 256; row += 8) {
    const cells = names
      .slice(row, row + 8)
      .map((n) => `"${n ?? ""}"`);
    rows.push(`    ${cells.join(", ")}, // 0x${row.toString(16).toUpperCase().padStart(2, "0")}`);
  }
  return `${doc}\npub(super) const ${name}: [&str; 256] = [\n${rows.join("\n")}\n];\n`;
}

writeFileSync(
  out,
  `//! The glyph names of the simple-font encodings (Annex D, 9.6.5.4). A code
//! with no glyph is \`""\`.
//!
//! Generated by \`scripts/pdf/gen-encodings.mjs\`; do not edit.

#![cfg_attr(rustfmt, rustfmt::skip)]

` +
    rust("STANDARD", "/// `StandardEncoding` (Annex D).", standard) +
    "\n" +
    rust(
      "WIN_ANSI",
      "/// `WinAnsiEncoding` (Annex D): space and hyphen also at `0xA0` and `0xAD`,\n/// and `bullet` at every unused code above octal 40.",
      winAnsi,
    ) +
    "\n" +
    rust(
      "MAC_ROMAN",
      "/// `MacRomanEncoding` (Annex D): space also at `0xCA`, and the Mac OS Roman\n/// entries of Table 113 but the Euro, as PDFium and pdf.js read it.",
      macRoman,
    ) +
    "\n" +
    rust(
      "MAC_OS_ROMAN",
      "/// The Mac OS Roman encoding (9.6.5.4, Table 113): `MAC_ROMAN` with the Euro\n/// at `0xDB`, which a TrueType font flagged symbolic reads by.",
      macOsRoman,
    ) +
    "\n" +
    rust("MAC_EXPERT", "/// `MacExpertEncoding` (Annex D).", macExpert),
);
console.log(`wrote ${out}`);
