// Generate `crates/elide-pdf/src/pdf/reader/font/standard/encodings.rs`: the
// glyph names of WinAnsiEncoding and MacRomanEncoding (ISO 32000-2, Annex D).
//
// The code-to-name pairs come from Apache PDFBox's encoding classes at a
// pinned commit, changed where PDFBox, Annex D, and the renderers differ:
//
// - WinAnsi 0xA0 and 0xAD are `space` and `hyphen` (PDFBox: `nbspace`,
//   `sfthyphen`, names the standard 14 AFMs do not have);
// - MacRoman 0xCA is `space` (PDFBox: `nbspace`);
// - MacRoman also has the Mac OS Roman entries of Table 113 but the Euro, as
//   PDFium and pdf.js read it (Annex D leaves those codes unused, and keeps
//   `currency` at 0xDB);
// - every WinAnsi code above octal 40 that Annex D leaves unused is `bullet`
//   (Annex D, note on WinAnsiEncoding; PDFBox does the same at runtime).
//
// Usage: node scripts/gen-pdf-encodings.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PDFBOX = "273e1ca7af365bf002b0189ddd1f476336853ac7";
const BASE = `https://raw.githubusercontent.com/apache/pdfbox/${PDFBOX}/pdfbox/src/main/java/org/apache/pdfbox/pdmodel/font/encoding`;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "crates/elide-pdf/src/pdf/reader/font/standard/encodings.rs");

// The `{0NNN, "name"}` pairs of a PDFBox encoding class, as a 256-entry table.
async function table(file) {
  const response = await fetch(`${BASE}/${file}`);
  if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
  const source = await response.text();
  const names = new Array(256).fill(null);
  for (const [, code, name] of source.matchAll(/\{(0[0-7]+), "([^"]+)"\}/g)) {
    names[parseInt(code, 8)] = name;
  }
  return names;
}

const winAnsi = await table("WinAnsiEncoding.java");
winAnsi[0xa0] = "space";
winAnsi[0xad] = "hyphen";
for (let code = 0o41; code <= 0xff; code++) winAnsi[code] ??= "bullet";

const macRoman = await table("MacRomanEncoding.java");
macRoman[0xca] = "space";
const macOs = {
  0xad: "notequal", 0xb0: "infinity", 0xb2: "lessequal", 0xb3: "greaterequal",
  0xb6: "partialdiff", 0xb7: "summation", 0xb8: "product", 0xb9: "pi",
  0xba: "integral", 0xbd: "Omega", 0xc3: "radical", 0xc5: "approxequal",
  0xc6: "Delta", 0xd7: "lozenge", 0xf0: "apple",
};
for (const [code, name] of Object.entries(macOs)) macRoman[code] = name;

function rust(name, doc, names) {
  const rows = [];
  for (let row = 0; row < 256; row += 8) {
    const cells = names
      .slice(row, row + 8)
      .map((n) => (n === null ? "None" : `Some("${n}")`));
    rows.push(`    ${cells.join(", ")}, // 0x${row.toString(16).toUpperCase().padStart(2, "0")}`);
  }
  return `${doc}\npub(super) const ${name}: [Option<&str>; 256] = [\n${rows.join("\n")}\n];\n`;
}

writeFileSync(
  out,
  `//! The glyph names of the predefined simple-font encodings a standard font
//! may be given (Annex D), besides the standard encoding, which is the
//! Latin faces' built-in one. A code with no glyph is \`None\`.
//!
//! Generated by \`scripts/gen-pdf-encodings.mjs\`; do not edit.

#![cfg_attr(rustfmt, rustfmt::skip)]

` +
    rust(
      "WIN_ANSI",
      "/// `WinAnsiEncoding` (Annex D): space and hyphen also at `0xA0` and `0xAD`,\n/// and `bullet` at every unused code above octal 40.",
      winAnsi,
    ) +
    "\n" +
    rust(
      "MAC_ROMAN",
      "/// `MacRomanEncoding` (Annex D): space also at `0xCA`, and the Mac OS Roman\n/// entries of Table 113 but the Euro, as PDFium and pdf.js read it.",
      macRoman,
    ),
);
console.log(`wrote ${out}`);
